#!/usr/bin/env bash
set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SAVE="$HOME/ckourse-stream-repro-backup"
BUNDLE="$ROOT/src-tauri/target/release/bundle/appimage"
APPDIR="$BUNDLE/ckourse.AppDir"
OUTPUT="$BUNDLE/ckourse_1.2.0_amd64.AppImage"
PLUGIN="$HOME/.cache/tauri/linuxdeploy-plugin-appimage.AppImage"
BUILD_LOG="$SAVE/appimage-build.log"
STAGED_OUTPUT="$BUNDLE/ckourse_1.2.0_amd64.postprocessed.AppImage"

mkdir -p "$SAVE"
cd "$ROOT"

if [[ ! -x "$PLUGIN" ]]; then
    echo "ERROR: AppImage packaging plugin not found: $PLUGIN" >&2
    exit 1
fi

echo "=== Building Ckourse ==="
rm -rf -- "$APPDIR"

set +e
npm run tauri:cli -- build "$@" 2>&1 | tee "$BUILD_LOG"
BUILD_STATUS=${PIPESTATUS[0]}
set -e

# Tauri can generate all Linux bundles, then return an error because
# the updater private signing key is not configured.
if (( BUILD_STATUS != 0 )); then
    if grep -Fq "A public key has been found, but no private key" "$BUILD_LOG" \
       && grep -Fq "Finished 3 bundles at:" "$BUILD_LOG"; then
        echo "WARNING: Linux bundles were generated, but updater signing is not configured."
        echo "Updater artifacts will not be generated by this build."
    else
        echo "ERROR: Tauri build failed. See $BUILD_LOG" >&2
        exit "$BUILD_STATUS"
    fi
fi

HOOK="$APPDIR/apprun-hooks/linuxdeploy-plugin-gstreamer.sh"

if [[ ! -f "$HOOK" ||
      ! -f "$APPDIR/usr/lib/ckourse/gstreamer/libgsttauriasset.so" ]]; then
    echo "ERROR: AppDir or custom GStreamer plugin is missing." >&2
    exit 1
fi

echo
echo "=== Fixing GStreamer plugin search path ==="
python3 - "$HOOK" <<'PY'
from pathlib import Path
import sys

path = Path(sys.argv[1])
text = path.read_text()

custom = '${APPDIR}/usr/lib/ckourse/gstreamer'
if custom in text:
    print("Custom plugin path is already present.")
else:
    old = 'export GST_PLUGIN_PATH_1_0="${APPDIR}/usr/lib/gstreamer-1.0"'
    new = f'export GST_PLUGIN_PATH_1_0="${{APPDIR}}/usr/lib/gstreamer-1.0:{custom}"'
    if text.count(old) != 1:
        raise SystemExit(
            "ERROR: Unexpected GStreamer hook format; refusing to patch it."
        )
    path.write_text(text.replace(old, new, 1))
    print("Added custom stream plugin directory to GST_PLUGIN_PATH_1_0.")
PY

echo
echo "=== Removing tested conflicting display libraries ==="
shopt -s nullglob
removed=0

patterns=(
    'libwayland-client.so*'
    'libwayland-cursor.so*'
    'libwayland-egl.so*'
    'libwayland-server.so*'
    'libxkbcommon.so*'
    'libxcb-randr.so*'
    'libxcb-render.so*'
    'libxcb-shm.so*'
    'libXau.so*'
    'libXdmcp.so*'
)

for pattern in "${patterns[@]}"; do
    for file in "$APPDIR/usr/lib/"$pattern; do
        [[ -e "$file" || -L "$file" ]] || continue
        echo "Removing bundled library: ${file##*/}"
        rm -f -- "$file"
        removed=$((removed + 1))
    done
done

echo "Removed $removed bundled display-library files."

echo
echo "=== Packaging patched AppDir ==="
rm -f -- "$STAGED_OUTPUT"

APPIMAGE_EXTRACT_AND_RUN=1 LDAI_OUTPUT="$STAGED_OUTPUT" \
    "$PLUGIN" --appdir="$APPDIR"

if [[ ! -s "$STAGED_OUTPUT" ]]; then
    echo "ERROR: AppImage packaging did not produce the expected output." >&2
    exit 1
fi

chmod +x "$STAGED_OUTPUT"
mv -f -- "$STAGED_OUTPUT" "$OUTPUT"

echo
echo "=== AppImage ready ==="
ls -lh "$OUTPUT"
echo "Build log: $BUILD_LOG"
